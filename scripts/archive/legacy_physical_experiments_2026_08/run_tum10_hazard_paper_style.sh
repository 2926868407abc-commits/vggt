RUN_EVAL="${RUN_EVAL:-1}" \
SCENE_PATTERN="${SCENE_PATTERN:-rgbd_dataset_freiburg3_sitting_static}" \
TUM_GEOM_RUN_NAME="${TUM_GEOM_RUN_NAME:-tum10_sitting_static_hazard_paperstyle_autopos_pose_gt_1000}" \
TUM_GEOM_MODEL="${TUM_GEOM_MODEL:-vggt_tum10_sitting_static_hazard_paperstyle_autopos_pose_gt_1000}" \
TUM_CLEAN_MODEL="${TUM_CLEAN_MODEL:-vggt_tum10_sitting_static_clean_uniform_l3}" \
ATTACK_LOSS="${ATTACK_LOSS:-pose_gt_untargeted}" \
ACTIVATION_CHECKPOINT="${ACTIVATION_CHECKPOINT:-0}" \
PLANE_MODE="${PLANE_MODE:-vggt_pointmap_surface}" \
SURFACE_SCORE_MODE="${SURFACE_SCORE_MODE:-natural}" \
SURFACE_COVERAGE_MIN="${SURFACE_COVERAGE_MIN:-0.006}" \
SURFACE_COVERAGE_MAX="${SURFACE_COVERAGE_MAX:-0.05}" \
SURFACE_MIN_VISIBLE_FRAMES="${SURFACE_MIN_VISIBLE_FRAMES:-4}" \
SURFACE_MIN_VISIBILITY_RATIO="${SURFACE_MIN_VISIBILITY_RATIO:-0.5}" \
SURFACE_ORIENTATION_FILTER="${SURFACE_ORIENTATION_FILTER:-fronto_or_tabletop}" \
SURFACE_MAX_TILT_DEGREES="${SURFACE_MAX_TILT_DEGREES:-45}" \
SURFACE_SUPPORT_CHECK="${SURFACE_SUPPORT_CHECK:-1}" \
SURFACE_SUPPORT_ABS_TOLERANCE="${SURFACE_SUPPORT_ABS_TOLERANCE:-0.08}" \
SURFACE_SUPPORT_REL_TOLERANCE="${SURFACE_SUPPORT_REL_TOLERANCE:-0.05}" \
SURFACE_MIN_SUPPORT_RATIO="${SURFACE_MIN_SUPPORT_RATIO:-0.55}" \
SURFACE_STRENGTH_SEARCH="${SURFACE_STRENGTH_SEARCH:-1}" \
SURFACE_STRENGTH_CANDIDATES="${SURFACE_STRENGTH_CANDIDATES:-12}" \
SURFACE_STRENGTH_STEPS="${SURFACE_STRENGTH_STEPS:-16}" \
SURFACE_STRENGTH_LR="${SURFACE_STRENGTH_LR:-0.002}" \
SURFACE_STRENGTH_TEXTURE_INIT="${SURFACE_STRENGTH_TEXTURE_INIT:-checker}" \
SURFACE_STRENGTH_REGULARIZATION_WEIGHT="${SURFACE_STRENGTH_REGULARIZATION_WEIGHT:-0.2}" \
VGGT_POINT_CONF_PERCENTILE="${VGGT_POINT_CONF_PERCENTILE:-40}" \
SURFACE_CANDIDATE_GRID="${SURFACE_CANDIDATE_GRID:-6}" \
FUSED_SURFACE_CANDIDATES="${FUSED_SURFACE_CANDIDATES:-128}" \
OPTIMIZE_GEOMETRY="${OPTIMIZE_GEOMETRY:-1}" \
GEOMETRY_SIZE_SCALES="${GEOMETRY_SIZE_SCALES:-0.75,1.0,1.25}" \
GEOMETRY_ROLL_DEGREES="${GEOMETRY_ROLL_DEGREES:--30,-15,0,15,30}" \
PLANE_WIDTH="${PLANE_WIDTH:-0.30}" \
