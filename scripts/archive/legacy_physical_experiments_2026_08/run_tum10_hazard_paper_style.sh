#!/usr/bin/env bash
set -Eeuo pipefail

VGGT_ROOT="${VGGT_ROOT:-/mnt/data/wangqq/vggt}"
TEXTURE_ROOT="${TEXTURE_ROOT:-$VGGT_ROOT/assets/hazard_textures}"
MDE_ATTACK_ROOT="${MDE_ATTACK_ROOT:-$VGGT_ROOT/_external_MDE_Attack}"
MDE_WARNING_TEXTURE="${MDE_WARNING_TEXTURE:-$MDE_ATTACK_ROOT/DeepPhotoStyle_pytorch/asset/src_img/style/Warnning.png}"
HAZARD_TEXTURE="${HAZARD_TEXTURE:-$TEXTURE_ROOT/mde_attack_warnning.png}"

mkdir -p "$TEXTURE_ROOT"

if [[ -f "$MDE_WARNING_TEXTURE" ]]; then
  cp "$MDE_WARNING_TEXTURE" "$HAZARD_TEXTURE"
  echo "Using MDE_Attack warning texture: $MDE_WARNING_TEXTURE"
elif [[ -f "$HAZARD_TEXTURE" ]]; then
  echo "Using existing warning texture: $HAZARD_TEXTURE"
else
  echo "MDE_Attack Warnning.png not found; generating fallback hazard texture: $HAZARD_TEXTURE"
  "${VGGT_PY:-/mnt/data/wangqq/conda_envs/vggt/bin/python3}" \
    "$VGGT_ROOT/scripts/make_hazard_stripe_texture.py" \
    --out "$HAZARD_TEXTURE" \
    --size "${HAZARD_SIZE:-256}" \
    --stripe_width "${HAZARD_STRIPE_WIDTH:-24}"
fi

echo "===== run hazard paper-style auto-position patch ====="
FORCE_PREPARE_TUM10="${FORCE_PREPARE_TUM10:-0}" \
FORCE_CLEAN="${FORCE_CLEAN:-0}" \
FORCE_TRAIN="${FORCE_TRAIN:-1}" \
